// 매칭용 정규화: 공백·가운뎃점 제거, 로마숫자→아라비아 숫자
function normName(s) {
  return String(s || '')
    .replace(/Ⅰ|Ⅰ/g, '1').replace(/Ⅱ/g, '2').replace(/Ⅲ/g, '3').replace(/([가-힣])\s*II$/, '$12').replace(/([가-힣])\s*I$/, '$11')
    .replace(/[\s·ㆍ‧∙•・.·]/g, '')
    .toLowerCase();
}

const SUBJECTS = []; // {name, norm, group, cur: Set}
const byNorm = new Map();
for (const [cur, table] of [['2022', S2022], ['2015', S2015]]) {
  for (const [group, list] of Object.entries(table)) {
    for (const name of list) {
      const n = normName(name);
      let e = byNorm.get(n);
      if (!e) { e = { name, norm: n, group, curs: [] }; byNorm.set(n, e); SUBJECTS.push(e); }
      if (!e.curs.includes(cur)) e.curs.push(cur);
    }
  }
}
// 긴 이름부터 매칭 (생명과학1 이 생명과학 보다 먼저)
SUBJECTS.sort((a, b) => b.norm.length - a.norm.length);

// 정규화된 문자열에서 과목명을 찾는다. 뒤 글자가 숫자면 더 긴 과목명이 있어야 하므로 거른다.
function findSubject(textNorm) {
  for (const s of SUBJECTS) {
    let i = textNorm.indexOf(s.norm);
    while (i >= 0) {
      const next = textNorm[i + s.norm.length] || '';
      const prev = textNorm[i - 1] || '';
      const okNext = !/[0-9]/.test(next) && !/^(과(?!목)|교과|탐구|실험|교육|공시|전공|통신|처리)/.test(textNorm.slice(i + s.norm.length));
      const okPrev = !/[가-힣]/.test(prev) || /[\[\]<>「」『』【】:：]/.test(prev) || /(년도|학년|학기|교과|과목|과목명)$/.test(textNorm.slice(0, i));
      if (okNext && okPrev) return s;
      i = textNorm.indexOf(s.norm, i + 1);
    }
  }
  return null;
}

function curriculumOf(subject, grade, year) {
  if (!subject) return { cur: '', ambiguous: true };
  if (subject.curs.length === 1) return { cur: subject.curs[0], ambiguous: false };
  if (grade && year) {
    const entry = year - grade + 1;
    return { cur: entry >= 2025 ? '2022' : '2015', ambiguous: false };
  }
  return { cur: subject.curs[0], ambiguous: true };
}

